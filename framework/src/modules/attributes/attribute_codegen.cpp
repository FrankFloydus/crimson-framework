/// Identifies files owned by the generator before an existing file is replaced.
constexpr std::string_view generated_marker = "// Generated by Crimson Gameplay Attributes. Edit the Project Settings registry and regenerate.";

/// Ensure the authored segment can safely appear in a C++ symbol, string and file name.
bool valid_symbol_segment(std::string_view segment) {
    return !segment.empty() && segment.front() >= 'a' && segment.front() <= 'z' && segment.back() != '_' &&
            segment.find("__") == std::string_view::npos &&
            std::all_of(segment.begin(), segment.end(), [](char c) {
                return (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_';
            });
}

/// Check every emitted symbol, including names shared by related attribute accessors.
bool validate_set_symbols(const AttributeSetDefinition &set, std::string &error) {
    if (!valid_symbol_segment(set.id)) {
        error = "Set ID '" + set.id + "' cannot be used in a generated C++ symbol.";
        return false;
    }
    std::map<std::string, std::string> owners;
    for (const auto &attribute : set.attributes) {
        const auto &id = attribute.id;
        const auto qualified_id = set.id + "." + id;
        if (!valid_symbol_segment(id)) {
            error = "Attribute ID '" + qualified_id + "' cannot be used in a generated C++ symbol.";
            return false;
        }
        for (const std::string &symbol : { id + "_id", "get_" + id, "get_" + id + "_base",
                     "set_" + id + "_base", "add_" + id + "_base", "bind_" + id + "_changed" }) {
            const auto inserted = owners.emplace(symbol, qualified_id);
            if (!inserted.second) {
                error = "C++ symbol '" + symbol + "' collides between '" + inserted.first->second +
                        "' and '" + qualified_id + "'.";
                return false;
            }
        }
    }
    return true;
}

/// Provide the shared Godot binding calls used by the header's attribute-specific helpers.
constexpr std::string_view binding_helpers = R"cpp(namespace detail {

/// Read one attribute property while retaining the snapshot for the duration of the call.
inline std::optional<double> read(godot::Object *attributes, const char *id, bool base) {
    if (!attributes) {
        return std::nullopt;
    }
    const godot::Variant snapshot = attributes->call("get_attribute", godot::StringName(id));
    auto *value = snapshot.get_validated_object();
    if (!value || (base && !static_cast<bool>(value->call("has_base")))) {
        return std::nullopt;
    }
    const godot::Variant number = value->call(base ? "get_base" : "get_current");
    if (number.get_type() != godot::Variant::FLOAT) {
        return std::nullopt;
    }
    return static_cast<double>(number);
}

/// Forward base edits to the same authority path as Godot's other callers.
inline godot::Error edit(godot::Object *attributes, const char *method, const char *id, double value) {
    if (!attributes) {
        return godot::ERR_UNAVAILABLE;
    }
    const godot::Variant result = attributes->call(method, godot::StringName(id), value);
    return result.get_type() == godot::Variant::INT
            ? static_cast<godot::Error>(static_cast<std::int64_t>(result))
            : godot::ERR_UNAVAILABLE;
}

/// Retain the native watch for as long as the caller keeps the returned subscription.
inline godot::Ref<godot::RefCounted> bind(godot::Object *attributes, const char *id, const godot::Callable &callback) {
    if (!attributes) {
        return {};
    }
    godot::Ref<godot::RefCounted> watch = attributes->call("watch_attribute", godot::StringName(id));
    if (watch.is_null() || watch->connect("changed", callback) != godot::OK) {
        return {};
    }
    return watch;
}

} // namespace detail

)cpp";

/// Render the same named operations over either a live set or a standalone attributes owner.
void append_attribute_accessors(std::ostringstream &out, std::string_view id, bool scoped) {
    const auto indent = scoped ? "    " : "";
    const auto qualifier = scoped ? "" : "inline ";
    const auto argument = scoped ? "" : "godot::Object &attributes";
    const auto delimiter = scoped ? "" : ", ";
    const auto suffix = scoped ? " const" : "";
    const auto receiver = scoped ? "attributes.ptr()" : "&attributes";
    const auto identifier = scoped ? "\"" + std::string(id) + "\"" : std::string(id) + "_id";

    out << indent << "/// Read the confirmed current value.\n"
        << indent << qualifier << "std::optional<double> get_" << id << "(" << argument << ")" << suffix << " {\n"
        << indent << "    return detail::read(" << receiver << ", " << identifier << ", false);\n"
        << indent << "}\n\n"
        << indent << "/// Read the base value when it is available to this caller.\n"
        << indent << qualifier << "std::optional<double> get_" << id << "_base(" << argument << ")" << suffix << " {\n"
        << indent << "    return detail::read(" << receiver << ", " << identifier << ", true);\n"
        << indent << "}\n\n"
        << indent << "/// Request a validated base replacement through the authority.\n"
        << indent << qualifier << "godot::Error set_" << id << "_base(" << argument << delimiter << "double value)" << suffix << " {\n"
        << indent << "    return detail::edit(" << receiver << ", \"set_base\", " << identifier << ", value);\n"
        << indent << "}\n\n"
        << indent << "/// Request a validated base adjustment through the authority.\n"
        << indent << qualifier << "godot::Error add_" << id << "_base(" << argument << delimiter << "double amount)" << suffix << " {\n"
        << indent << "    return detail::edit(" << receiver << ", \"add_base\", " << identifier << ", amount);\n"
        << indent << "}\n\n"
        << indent << "/// Keep the returned watch alive to receive changed(previous, current) after publication.\n"
        << indent << qualifier << "godot::Ref<godot::RefCounted> bind_" << id << "_changed(" << argument << delimiter
        << "const godot::Callable &callback)" << suffix << " {\n"
        << indent << "    return detail::bind(" << receiver << ", " << identifier << ", callback);\n"
        << indent << "}\n\n";
}

/// Generate source from IDs sorted by lexical order, independent of labels and editor order.
GeneratedAttributeHeader render_set(const AttributeSetDefinition &set) {
    std::vector<std::string_view> ids;
    ids.reserve(set.attributes.size());
    for (const auto &attribute : set.attributes) {
        ids.emplace_back(attribute.id);
    }
    std::sort(ids.begin(), ids.end());

    const std::string scope = set.id + "_attributes";
    std::ostringstream out;
    out << generated_marker << "\n\n#pragma once\n\n"
        << "#include <godot_cpp/classes/ref.hpp>\n"
        << "#include <godot_cpp/classes/ref_counted.hpp>\n"
        << "#include <godot_cpp/variant/callable.hpp>\n"
        << "#include <godot_cpp/variant/variant.hpp>\n\n"
        << "#include <cstdint>\n#include <optional>\n#include <utility>\n\n"
        << "namespace crimson::generated::" << scope << " {\n\n"
        << binding_helpers;
    for (const auto id : ids) {
        out << "/// Stable ID used by saves, replication and the Crimson bindings.\n"
            << "inline constexpr char " << id << "_id[] = \"" << set.id << "." << id << "\";\n\n";
        append_attribute_accessors(out, id, false);
    }
    out << "/// Typed handle for this set on an actor's Ability System Component.\n"
        << "class Set {\n"
        << "    /// Live set view retained for the lifetime of this handle.\n"
        << "    godot::Ref<godot::RefCounted> attributes;\n\n"
        << "    /// Wrap a live view returned by the component.\n"
        << "    explicit Set(godot::Ref<godot::RefCounted> view) : attributes(std::move(view)) {}\n\n"
        << "    friend std::optional<Set> find_set(godot::Object &component);\n\n"
        << "public:\n";
    for (const auto id : ids) {
        append_attribute_accessors(out, id, true);
    }
    out << "};\n\n"
        << "/// Find this live set on the supplied component, or return an empty optional.\n"
        << "inline std::optional<Set> find_set(godot::Object &component) {\n"
        << "    godot::Ref<godot::RefCounted> view = component.call(\"get_attribute_set\", godot::StringName(\"" << set.id << "\"));\n"
        << "    if (view.is_null()) {\n"
        << "        return std::nullopt;\n"
        << "    }\n"
        << "    return Set(std::move(view));\n"
        << "}\n\n";
    out << "} // namespace crimson::generated::" << scope << "\n";
    return { scope + ".gen.hpp", out.str() };
}

/// Resolve a Godot UTF-8 string to a path understood by the native file API.
fs::path native_path(const String &path) {
    const auto bytes = path.utf8();
    return fs::u8path(bytes.get_data(), bytes.get_data() + bytes.length());
}

/// Compare path components after resolving links and relative segments.
bool in_project(const fs::path &directory, const fs::path &project) {
    return std::mismatch(project.begin(), project.end(), directory.begin(), directory.end()).first == project.end();
}

/// Read an existing output only after confirming the generator owns it.
Error existing_source(const fs::path &path, bool &exists, std::string &source) {
    std::error_code status_error;
    const auto status = fs::symlink_status(path, status_error);
    if (status.type() == fs::file_type::not_found) {
        exists = false;
        return OK;
    }
    if (status_error || !fs::is_regular_file(status)) {
        return ERR_ALREADY_EXISTS;
    }
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        return ERR_FILE_CANT_READ;
    }
    std::getline(file, source);
    std::string_view first_line = source;
    if (!first_line.empty() && first_line.back() == '\r') {
        first_line.remove_suffix(1);
    }
    if (!file || first_line != generated_marker) {
        return ERR_ALREADY_EXISTS;
    }
    source.push_back('\n');
    source.append(std::istreambuf_iterator<char>(file), std::istreambuf_iterator<char>());
    exists = true;
    return file.bad() ? ERR_FILE_CANT_READ : OK;
}

/// Prepare a file path for an atomic replacement once its complete contents are staged.
struct HeaderWrite {
    /// Existing generated file or new destination.
    fs::path destination;
    /// Unique temporary sibling used for publication.
    fs::path temporary;
    /// Unique temporary sibling containing the original bytes for rollback.
    fs::path backup;
    /// Source associated with this output plan.
    const GeneratedAttributeHeader *entry = nullptr;
    /// Original bytes when replacing an existing header.
    std::optional<std::string> original;
    /// Track which temporary files this generation owns and must clean up.
    bool staged = false;
    bool backed_up = false;
    bool published = false;
};

/// Write a complete sibling file before replacing any destination.
bool stage_file(const fs::path &path, const std::string &source, bool &owned) {
    std::ofstream file(path, std::ios::binary);
    owned = file.is_open();
    file.write(source.data(), static_cast<std::streamsize>(source.size()));
    file.close();
    return static_cast<bool>(file);
}

/// Remove the temporary siblings written by this run after publication or recovery.
void discard_temporary_headers(const std::vector<HeaderWrite> &writes) {
    for (const auto &write : writes) {
        std::error_code ignored;
        if (write.staged) {
            fs::remove(write.temporary, ignored);
        }
        if (write.backed_up) {
            fs::remove(write.backup, ignored);
        }
    }
}

/// Restore published headers and identify any backup that must be recovered manually.
String rollback_headers(std::vector<HeaderWrite> &writes, const std::string &suffix) {
    String failures;
    for (auto it = writes.rbegin(); it != writes.rend(); ++it) {
        auto &write = *it;
        if (!write.published) {
            continue;
        }
        std::error_code restore_error;
        if (write.backed_up) {
            fs::rename(write.backup, write.destination, restore_error);
        } else {
            fs::remove(write.destination, restore_error);
        }
        if (restore_error) {
            failures += String("\nRollback failed for ") + String(write.entry->filename.c_str()) + String(".");
            if (write.backed_up) {
                failures += String(" The original is in ") +
                        String((write.entry->filename + suffix + ".previous").c_str()) + String(".");
                write.backed_up = false;
            }
        }
    }
    return failures;
}

