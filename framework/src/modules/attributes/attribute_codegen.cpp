bool validate_attribute_header_symbols(const AttributeRegistry &registry, std::string &error) {
    error.clear();
    std::set<std::string_view> set_ids;
    for (const auto &set : registry.sets) {
        if (!validate_set_symbols(set, error)) {
            return false;
        }
        if (!set_ids.emplace(set.id).second) {
            error = "Duplicate attribute set ID '" + set.id + "'.";
            return false;
        }
    }
    return true;
}

bool build_attribute_headers(const AttributeRegistry &registry, std::vector<GeneratedAttributeHeader> &headers,
        std::string &error) {
    if (!validate_attribute_header_symbols(registry, error)) {
        return false;
    }
    std::vector<const AttributeSetDefinition *> sets;
    sets.reserve(registry.sets.size());
    for (const auto &set : registry.sets) {
        sets.push_back(&set);
    }
    std::sort(sets.begin(), sets.end(), [](const AttributeSetDefinition *left, const AttributeSetDefinition *right) {
        return left->id < right->id;
    });
    std::vector<GeneratedAttributeHeader> generated;
    generated.reserve(sets.size());
    for (const auto *set : sets) {
        generated.push_back(render_set(*set));
    }
    headers = std::move(generated);
    return true;
}

godot::Error generate_attribute_headers(const AttributeRegistry &registry, const godot::String &directory,
        godot::String &error) {
    error = String();
    std::vector<GeneratedAttributeHeader> headers;
    std::string invalid;
    if (!build_attribute_headers(registry, headers, invalid)) {
        error = String::utf8(invalid.c_str());
        return ERR_INVALID_DATA;
    }

    auto *settings = ProjectSettings::get_singleton();
    std::error_code path_error;
    const auto project = fs::canonical(native_path(settings->globalize_path("res://")), path_error);
    if (path_error || !directory.begins_with("res://")) {
        error = "Choose a generated source directory inside the project.";
        return ERR_INVALID_PARAMETER;
    }
    const auto output = fs::weakly_canonical(native_path(settings->globalize_path(directory)), path_error);
    if (path_error || !in_project(output, project)) {
        error = "Choose a generated source directory inside the project.";
        return ERR_INVALID_PARAMETER;
    }

    static std::atomic<uint64_t> next_write{0};
    const auto suffix = ".tmp-" + std::to_string(OS::get_singleton()->get_process_id()) + "-" +
            std::to_string(Time::get_singleton()->get_ticks_usec()) + "-" +
            std::to_string(next_write.fetch_add(1, std::memory_order_relaxed));
    std::vector<HeaderWrite> writes;
    for (const auto &header : headers) {
        const auto target = output / header.filename;
        std::string original;
        bool exists = false;
        const auto read_error = existing_source(target, exists, original);
        if (read_error != OK) {
            error = String("Cannot replace ") + String(header.filename.c_str()) +
                    String(". Choose an output directory without conflicting files.");
            return read_error;
        }
        if (!exists || original != header.source) {
            auto temporary = target;
            temporary += suffix;
            auto backup = target;
            backup += suffix + ".previous";
            writes.push_back({ target, std::move(temporary), std::move(backup), &header,
                    exists ? std::optional(std::move(original)) : std::nullopt });
        }
    }
    if (writes.empty()) {
        return OK;
    }
    fs::create_directories(output, path_error);
    if (path_error) {
        error = String("Could not create the generated source directory ") + directory + String(".");
        return ERR_CANT_CREATE;
    }
    for (auto &write : writes) {
        if (!stage_file(write.temporary, write.entry->source, write.staged) ||
                (write.original && !stage_file(write.backup, *write.original, write.backed_up))) {
            discard_temporary_headers(writes);
            error = String("Could not stage ") + String(write.entry->filename.c_str()) + String(".");
            return ERR_FILE_CANT_WRITE;
        }
    }
    for (auto &write : writes) {
        fs::rename(write.temporary, write.destination, path_error);
        if (path_error) {
            const auto rollback_failures = rollback_headers(writes, suffix);
            error = String("Could not publish ") + String(write.entry->filename.c_str()) +
                    String(". Check permissions and run Generate again.") + rollback_failures;
            discard_temporary_headers(writes);
            return ERR_FILE_CANT_WRITE;
        }
        write.staged = false;
        write.published = true;
    }
    discard_temporary_headers(writes);
    return OK;
}

